// Builds src/data/gaWindows.generated.ts from the monthly "what to plant" lists
// captured from ABC Gardening Australia's Vegie Guide (one file per zone,
// one line per month: "<month>|<comma-separated names as published>").
// Run: node scripts/build-ga-windows.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const ZONES = {
  tropical: 'ga_tropical.txt',
  subtropical: 'ga_subtropical.txt',
  'warm-temperate': 'ga_temperate.txt',
  'cool-temperate': 'ga_cool.txt',
  arid: 'ga_arid.txt',
};

// Published name (lower-case, normalised) → catalogue plant ids.
const MAP = [
  [/^tomatoes$/, ['tomato', 'cherry-tomato']],
  [/^capsicum$/, ['capsicum']],
  [/^chilli$/, ['chilli']],
  [/^eggplant$/, ['eggplant']],
  [/^zucchini$/, ['zucchini']],
  [/^pumpkin$/, ['pumpkin']],
  [/^cucumber$/, ['cucumber']],
  [/^carrots$/, ['carrot']],
  [/^radish$/, ['radish']],
  [/^beetroot$/, ['beetroot']],
  [/^lettuce$/, ['lettuce']],
  [/^spinach$/, ['spinach']],
  [/^(silverbeet|silver beet)$/, ['silverbeet']],
  [/^kale$/, ['kale']],
  [/^(beans \/ climbing (&|and) bush|beans \(climbing and bush\)|climbing beans \/ dwarf \(french\) beans)$/, ['bean-bush', 'bean-climbing']],
  [/^broad beans$/, ['broad-bean']],
  [/^(peas\/snow peas|peas)$/, ['pea']],
  [/^sweet corn$/, ['sweet-corn']],
  [/^potatoes$/, ['potato']],
  [/^sweet potato$/, ['sweet-potato']],
  [/^onion$/, ['onion']],
  [/^garlic$/, ['garlic']],
  [/^spring onions$/, ['spring-onion']],
  [/^leeks$/, ['leek']],
  [/^broccoli$/, ['broccoli']],
  [/^cauliflower$/, ['cauliflower']],
  [/^cabbage( \(loose-headed\)| \(tight-headed\)| \(loose headed\))?$/, ['cabbage']],
  [/^rocket$/, ['rocket']],
  [/^pak choy$/, ['pak-choy']],
  [/^basil$/, ['basil']],
  [/^parsley$/, ['parsley']],
  [/^coriander$/, ['coriander']],
  [/^chives$/, ['chives']],
  [/^oregano$/, ['oregano']],
  [/^sunflower$/, ['sunflower']],
  [/^(warrigal greens|nz spinach|warrigal greens \/ nz spinach)$/, ['warrigal-greens']],
];

const out = {};
const unmatched = new Set();
for (const [zone, file] of Object.entries(ZONES)) {
  const lines = readFileSync(new URL(`../data-sources/gardening-australia/${file}`, import.meta.url), 'utf8')
    .split('\n')
    .filter(Boolean);
  for (const line of lines) {
    const [mStr, list] = line.split('|');
    const month = Number(mStr);
    for (const raw of list.split(',')) {
      const name = raw.trim().toLowerCase().replace(/\s+/g, ' ');
      if (!name) continue;
      const hit = MAP.find(([re]) => re.test(name));
      if (!hit) {
        unmatched.add(name);
        continue;
      }
      for (const id of hit[1]) {
        out[id] ??= {};
        out[id][zone] ??= new Set();
        out[id][zone].add(month);
      }
    }
  }
}

const ser = {};
for (const [id, zones] of Object.entries(out)) {
  ser[id] = {};
  for (const [z, set] of Object.entries(zones)) ser[id][z] = [...set].sort((a, b) => a - b);
}

const header = `/* AUTO-GENERATED by scripts/build-ga-windows.mjs — do not edit by hand.
 * Source: ABC Gardening Australia Vegie Guide, monthly planting lists per zone
 * (https://www.abc.net.au/gardening/vegie-guide-zones/9796680), captured 2026-09-24.
 * Zone mapping: GA Temperate → warm-temperate, GA Cool → cool-temperate.
 * These months are when GA lists the crop as suitable to plant/sow.
 */
import type { ClimateZoneId, Month } from '../domain/types';

export const GA_WINDOWS: Record<string, Partial<Record<ClimateZoneId, Month[]>>> = `;
writeFileSync(
  new URL('../src/data/gaWindows.generated.ts', import.meta.url),
  header + JSON.stringify(ser, null, 2).replace(/\[\s*([\d,\s]+?)\s*\]/g, (_, g) => '[' + g.replace(/\s+/g, '').replace(/,/g, ', ') + ']') + ' as Record<string, Partial<Record<ClimateZoneId, Month[]>>>;\n',
);
console.log('plants:', Object.keys(ser).length);
console.log('unmatched (not in catalogue):', [...unmatched].sort().join('; '));
