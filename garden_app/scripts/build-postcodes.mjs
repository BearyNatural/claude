// Builds src/data/postcodes.generated.ts from the GeoNames Australian postal
// code file (CC BY 4.0, https://www.geonames.org — credit is shown in the app).
//   1. Download https://download.geonames.org/export/zip/AU.zip and unzip it.
//   2. Run: node scripts/build-postcodes.mjs path/to/AU.txt
// Postal-only names (delivery/business/mail centres, PO boxes) are dropped;
// coordinates are rounded to 2 d.p. (≈1 km), like the rest of the app.
import { readFileSync, writeFileSync } from 'node:fs';

const src = process.argv[2];
if (!src) {
  console.error('Usage: node scripts/build-postcodes.mjs path/to/AU.txt');
  process.exit(1);
}

const STATES = new Set(['ACT', 'NSW', 'NT', 'QLD', 'SA', 'TAS', 'VIC', 'WA']);
const POSTAL_ONLY = / (Dc|Bc|Mc|Po|Lpo|Delivery Centre|Mail Centre|Business Centre)$/i;

// postcode → { state, places: Map<name, [lat, lon]> }
const byPostcode = new Map();
let kept = 0;
for (const line of readFileSync(src, 'utf8').split('\n')) {
  const f = line.split('\t');
  if (f.length < 11) continue;
  const [, postcode, name, , state] = f;
  const lat = Number(f[9]);
  const lon = Number(f[10]);
  if (!/^\d{4}$/.test(postcode) || !STATES.has(state) || !name || POSTAL_ONLY.test(name)) continue;
  if (!Number.isFinite(lat) || !Number.isFinite(lon)) continue;
  const clean = name.replace(/[|;:]/g, ' ').trim();
  let entry = byPostcode.get(postcode);
  if (!entry) byPostcode.set(postcode, (entry = { state, places: new Map() }));
  if (entry.places.has(clean)) continue;
  entry.places.set(clean, [Math.round(lat * 100), Math.round(lon * 100)]);
  kept++;
}

// One line per postcode: "<postcode>|<state>|<name>:<lat×100>:<lon×100>;…"
const lines = [...byPostcode.entries()]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([pc, { state, places }]) => `${pc}|${state}|${[...places.entries()].sort(([a], [b]) => a.localeCompare(b)).map(([n, [la, lo]]) => `${n}:${la}:${lo}`).join(';')}`);

const out = `/* AUTO-GENERATED by scripts/build-postcodes.mjs — do not edit by hand.
 * Source: GeoNames Australian postal codes (https://download.geonames.org/export/zip/AU.zip),
 * licensed CC BY 4.0 (https://creativecommons.org/licenses/by/4.0/). Downloaded ${new Date().toISOString().slice(0, 10)}.
 * ${byPostcode.size} postcodes, ${kept} suburbs/localities. Postal-only names removed.
 * Format: one line per postcode — "<postcode>|<state>|<name>:<lat×100>:<lon×100>;…"
 */
export const POSTCODE_DATA = ${JSON.stringify(lines.join('\n'))};
`;
writeFileSync(new URL('../src/data/postcodes.generated.ts', import.meta.url), out);
console.log(`Wrote ${byPostcode.size} postcodes, ${kept} places.`);
